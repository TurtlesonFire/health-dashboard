/**
 * Verify the deployed static site works with NO backend.
 *
 * This exercises the REAL frontend module (frontend/src/api.js compiled into
 * the static bundle) against a plain static server, rather than re-implementing
 * its URL logic — a hand-rolled copy would pass while the shipped code is wrong.
 *
 * Build and serve first:
 *   cd frontend && VITE_DATA_MODE=static npx vite build
 *   cd dist && python -m http.server 4180
 */
import { STATIC, DIST } from './env.mjs'

const BASE = STATIC

let pass = 0
let fail = 0
const check = (name, ok, detail = '') => {
  if (ok) { pass++; console.log(`  PASS  ${name}${detail ? '  — ' + detail : ''}`) }
  else { fail++; console.log(`  FAIL  ${name}${detail ? '  — ' + detail : ''}`) }
}

// The bundle inlines VITE_DATA_MODE at build time, so import the built chunk
// and drive it through its public surface.
const fs = await import('node:fs')
const path = await import('node:path')

const ASSETS = DIST
const apiChunk = fs.readdirSync(ASSETS).find((f) => /^api-.*\.js$/.test(f))
const src = fs.readFileSync(path.join(ASSETS, apiChunk), 'utf8')

console.log('='.repeat(78))
console.log('Static build — shipped bundle inspection')
console.log('='.repeat(78))
console.log(`  chunk: ${apiChunk} (${(src.length / 1024).toFixed(1)} KB)`)

// The static branch must be compiled in, and the proxy-dependent branch must
// not be reachable — i.e. VITE_DATA_MODE=static was actually baked in.
check('static mode compiled in (pre-rendered-data guard present)',
  src.includes('no pre-rendered data for'))
check('builds .json URLs', src.includes('.json'))

// Vite inlines `import.meta.env.VITE_DATA_MODE` as a literal, so Rollup
// constant-folds IS_STATIC to true and dead-code-eliminates the API branch.
// The proof is that the mode variable is GONE from the output and fetchJSON
// delegates to staticUrl unconditionally — asserting on the literal "static"
// would be wrong, since folding removes it.
check('mode constant folded away (no runtime VITE_DATA_MODE lookup)',
  !src.includes('VITE_DATA_MODE'))

// fetchJSON must call staticUrl directly, with no `?` branch left over.
const fetchBody = src.match(/async function \w+\(e,t\)\{[^}]*?fetch\(/)
const delegatesUnconditionally = /const \w+=_\w+\(e,t\),\w+=await fetch\(/.test(src)
check('fetchJSON delegates to staticUrl with no conditional branch',
  delegatesUnconditionally, fetchBody ? fetchBody[0].slice(0, 70) + '…' : 'pattern not found')

// ============================================================================
console.log()
console.log('='.repeat(78))
console.log('Every request the app makes resolves to a real file (no backend)')
console.log('='.repeat(78))

// Reproduce exactly the paths api.js builds in static mode: `<path>.json`.
const REQUESTED = [
  ['/indicators', 'indicators.json'],
  ['/metric-info', 'metric-info.json'],
  ['/categories', 'categories.json'],
  ['/sources', 'sources.json'],
  ['/data/WHOSIS_000001', 'data/WHOSIS_000001.json'],
  ['/data/MDG_0000000007', 'data/MDG_0000000007.json'],
  ['/data/SP.POP.TOTL', 'data/SP.POP.TOTL.json'],
  ['/data/NY.GDP.PCAP.CN', 'data/NY.GDP.PCAP.CN.json'],
  ['/data/UHC_INDEX_REPORTED', 'data/UHC_INDEX_REPORTED.json'],
  ['/data/MDG_0000000007/quintiles', 'data/MDG_0000000007/quintiles.json'],
]

for (const [apiPath, filePath] of REQUESTED) {
  const url = `${BASE}/api/${filePath}`
  try {
    const r = await fetch(url)
    const body = await r.json()
    const n = Array.isArray(body) ? `${body.length} rows` : `${Object.keys(body).length} keys`
    check(`${apiPath} -> ${filePath}`, r.ok, `${r.status} ${n}`)
  } catch (e) {
    check(`${apiPath} -> ${filePath}`, false, e.message)
  }
}

// ============================================================================
console.log()
console.log('='.repeat(78))
console.log('Static payloads carry the same data as the live API')
console.log('='.repeat(78))

// The static files were generated by running the real endpoints through
// TestClient, so values must match what the API served.
const quint = await (await fetch(`${BASE}/api/data/MDG_0000000007/quintiles.json`)).json()
check('quintile payload has 6 series (Q1..Q5 + TOTAL)',
  quint.series?.length === 6, `${quint.series?.length} series`)
check('equity ratio preserved', quint.equity_ratio === 2.78,
  `equity_ratio=${quint.equity_ratio}`)
check('latest_year preserved', quint.latest_year === 2024,
  `latest_year=${quint.latest_year}`)

const q1 = quint.series.find((s) => s.code === 'Q1')
const p2024 = q1.points.find((p) => p.year === 2024)
check('Q1 2024 value intact', Math.abs(p2024.value - 39.14) < 0.01,
  `Q1 2024 = ${p2024.value}`)

const ind = await (await fetch(`${BASE}/api/indicators.json`)).json()
// 32 WHO/World Bank indicators plus the 21 the PSA source adds: the all-cause
// total, nineteen ICD-10 chapters and the residual "other causes" bucket.
check('all 53 indicators exported', ind.length === 53, `${ind.length}`)
check('regional indicators exported',
  ind.filter((i) => i.category === 'regional').length === 21,
  `${ind.filter((i) => i.category === 'regional').length} regional`)

const info = await (await fetch(`${BASE}/api/metric-info.json`)).json()
check('metric blurbs exported', Object.keys(info).length >= 52,
  `${Object.keys(info).length} blurbs`)
check('every PSA indicator has a blurb',
  ind.filter((i) => i.source === 'psa')
    .every((i) => info[i.code]?.what && info[i.code]?.how),
  `${ind.filter((i) => i.source === 'psa').length} PSA indicators`)
check('UHC blurb intact', Boolean(info.UHC_INDEX_REPORTED?.how))

const peso = await (await fetch(`${BASE}/api/data/NY.GDP.PCAP.CN.json`)).json()
const p24 = peso.find((r) => r.year === 2024)
check('peso series intact', Math.abs(p24.value - 228320.14) < 1,
  `2024 = ${p24.value}`)

// ============================================================================
console.log()
console.log('='.repeat(78))
console.log('Regional payloads (Module 4)')
console.log('='.repeat(78))

// Module 4 is the dashboard's subnational view and the payload most likely to
// rot silently: it comes from a separate exporter pass and a code-split chunk,
// so a missing file surfaces as an empty tab rather than as an error.
const regional = await (await fetch(`${BASE}/api/data/PSA_DEATHS_ALL_CAUSES/regions.json`)).json()
check('regional payload has 18 regions', regional.regions?.length === 18,
  `${regional.regions?.length} regions`)
check('regional payload carries the national total', Boolean(regional.national))
check('national 2024 intact',
  Math.abs(regional.national?.latest_value - 701884) < 1,
  `${regional.national?.latest_value}`)
check('regions ranked descending',
  regional.regions.every((r, i, a) => i === 0 || a[i - 1].latest_value >= r.latest_value))
check('every region name is a real region, not the national name',
  regional.regions.every((r) => r.region_name && r.region_name !== 'Philippines'),
  `${regional.regions.length} names`)
// NIR exists only from 2024. Asserting the gap is deliberate: an invented
// history would mean the ETL is fabricating years.
check('NIR has no history before it existed',
  regional.regions.find((r) => r.region_code === '1800000000')?.points?.length === 1)

const causes = await (await fetch(`${BASE}/api/regions/1900000000/causes.json`)).json()
check('cause profile names its region', causes.region_name?.startsWith('Bangsamoro'))
check('cause profile reports the all-cause total', causes.all_causes === 5552,
  `${causes.all_causes}`)
check('causes are ranked descending',
  causes.causes.every((c, i, a) => i === 0 || a[i - 1].value >= c.value))
// The payload is the top 10 of 20 causes, so the values cannot sum to the
// total. What must hold instead is that each share is that cause's value
// divided by the region's OWN all-cause total — the check that shares are not
// computed against some other denominator and then presented as shares of the
// region.
const top = causes.causes[0]
check('cause shares are computed against the region total',
  Math.abs(top.share - (100 * top.value) / causes.all_causes) < 0.01,
  `${top.share}% vs ${((100 * top.value) / causes.all_causes).toFixed(2)}%`)
check('cause payload is a bounded top-N slice of valid shares',
  causes.causes.length <= 10 &&
  causes.causes.every((c) => c.share > 0 && c.share <= 100))

// ============================================================================
console.log()
console.log('='.repeat(78))
console.log('No backend dependency remains')
console.log('='.repeat(78))

// The backend was never contacted: the static server only serves files. If any
// request had gone to :8000 it would have been a cross-origin fetch to a
// different port, which is not configured anywhere in the bundle.
check('bundle has no localhost:8000 reference', !src.includes('localhost:8000'))
check('API_BASE resolves to /health-dashboard/api (subpath deploy)',
  src.includes('health-dashboard/api'))
const entry = fs.readdirSync(ASSETS).find((f) => /^index-.*\.js$/.test(f))
const entrySrc = fs.readFileSync(path.join(ASSETS, entry), 'utf8')
check('entry chunk has no backend host either',
  !entrySrc.includes('localhost:8000') && !entrySrc.includes('127.0.0.1'))

console.log()
console.log('='.repeat(78))
console.log(`RESULT: ${pass} passed, ${fail} failed`)
console.log('='.repeat(78))
process.exit(fail === 0 ? 0 : 1)
